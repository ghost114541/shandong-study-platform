import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { setTimeout as delay } from 'node:timers/promises'

export async function tableRegression({ start, close, nativeClose, click, evaluate, send, status, snapshot, waitFor, fillFormula, out, database }) {
  assert.ok(readFileSync(database).length, 'Use a seeded isolated DEV-013 profile')
  const setCell = (row, column) => evaluate(`(() => {
    const p = document.querySelector('.tiptap table').rows[${row}].cells[${column}].querySelector('p')
    p.closest('.tiptap').focus()
    window.getSelection().collapse(p, p.childNodes.length)
    document.dispatchEvent(new Event('selectionchange'))
    return true
  })()`)
  const dimensions = () => evaluate("Array.from(document.querySelector('.tiptap table')?.rows ?? [], r => r.cells.length)")
  const hasSize = (rows, cols) => waitFor(async () => {
    const sizes = await dimensions()
    return sizes.length === rows && sizes.every((size) => size === cols)
  }, `table ${rows}×${cols}`)
  const invoke = (name, args) => evaluate('window.__TAURI_INTERNALS__.invoke(' + JSON.stringify(name) + ',' + JSON.stringify(args) + ')')
  const insert = (text) => send('Input.insertText', { text })
  const key = async (key, code, windowsVirtualKeyCode, modifiers = 0) => {
    for (const type of ['rawKeyDown', 'keyUp']) await send('Input.dispatchKeyEvent', { type, key, code, windowsVirtualKeyCode, modifiers })
  }
  const current = (id) => invoke('current_revision', { questionId: id }).then(({ revision }) => revision)
  const open = async (id) => {
    const selector = JSON.stringify(`[data-question-id="${id}"]`)
    await waitFor(() => evaluate(`Boolean(document.querySelector(${selector})?.matches(':enabled'))`), id)
    await evaluate(`document.querySelector(${selector}).click()`)
    await waitFor(() => evaluate(`Boolean(document.querySelector(${selector})?.matches('[aria-pressed=true]:enabled'))`), 'selected ' + id)
  }

  await start()
  await click('新建试题')
  await click('插入表格')
  await hasSize(2, 2)
  await setCell(0, 0)
  await click('下方加行')
  await click('右侧加列')
  await click('右侧加列')
  await hasSize(3, 4)
  await setCell(0, 0)
  await click('粗体')
  await click('斜体')
  await insert('中文 ABC 123')
  await key('Tab', 'Tab', 9)
  await insert('TAB-to-second-cell')
  await key('Enter', 'Enter', 13)
  await insert('换行 456')
  await click('插入行内公式')
  await fillFormula('x^2+12')
  const contents = () => evaluate("Array.from(document.querySelector('.tiptap table').rows[0].cells, c => c.textContent)")
  assert.equal((await contents())[0], '中文 ABC 123')
  assert.match((await contents())[1], /TAB-to-second-cell换行 456/)
  assert.equal(await evaluate("document.querySelector('.tiptap table th strong em, .tiptap table th em strong')?.textContent"), '中文 ABC 123')
  assert.equal(await evaluate("document.querySelector('.tiptap table th:nth-child(2) .katex') !== null"), true)

  await delay(600)
  await setCell(2, 3)
  await click('删除行')
  await hasSize(2, 4)
  await click('撤销')
  await hasSize(3, 4)
  await click('重做')
  await hasSize(2, 4)
  await delay(600)
  await setCell(1, 3)
  await click('删除列')
  await hasSize(2, 3)
  await click('撤销')
  await hasSize(2, 4)
  await click('重做')
  await hasSize(2, 3)
  await setCell(1, 2)
  await click('下方加行')
  await click('右侧加列')
  await hasSize(3, 4)
  assert.match((await contents())[1], /TAB-to-second-cell/)
  await snapshot('01-table-editor')

  const htmlBlocked = await evaluate(`(() => {
    const data = new DataTransfer()
    data.setData('text/html', '<table onclick="alert(1)"><tr><td><img src="https://example.invalid/a.png">unsafe</td></tr></table>')
    const event = new ClipboardEvent('paste', {clipboardData: data, bubbles: true, cancelable: true})
    document.querySelector('.tiptap').dispatchEvent(event)
    return event.defaultPrevented && !document.querySelector('.tiptap img[src*="example.invalid"]')
  })()`)
  assert.equal(htmlBlocked, true)
  await hasSize(3, 4)
  await click('保存到 SQLite')
  await status('已保存 SQLite 修订')
  const [item] = await invoke('list_questions', { limit: 1 })
  const first = await current(item.id)
  assert.equal(first.content.schema_version, 2)
  await close()
  await start()
  await open(item.id)
  await hasSize(3, 4)
  assert.deepEqual(await current(item.id), first)
  await snapshot('02-reopened-table')

  await setCell(2, 3)
  await insert('DEV013-AUTOSAVE')
  await status('草稿已安全保存')
  nativeClose()
  await click('保留草稿并离开')
  await delay(1500)
  await start()
  await click('查看可恢复草稿')
  await click('恢复草稿')
  await status('已恢复试题草稿')
  assert.match(await evaluate("document.querySelector('.tiptap table').textContent"), /DEV013-AUTOSAVE/)
  await snapshot('03-recovered-table-draft')
  await click('保存到 SQLite')
  await status('已保存 SQLite 修订')
  const second = await current(item.id)
  assert.equal(second.base_revision_id, first.id)
  assert.deepEqual((await invoke('read_revision', { revisionId: first.id })).revision, first)
  assert.match(JSON.stringify(second.content), /DEV013-AUTOSAVE/)

  await setCell(0, 0)
  await click('删除表格')
  await hasSize(0, 0)
  await click('撤销')
  await hasSize(3, 4)
  await click('保存到 SQLite')
  await status('已保存 SQLite 修订')
  writeFileSync(join(out, 'editor-results.json'), JSON.stringify({ first, second, htmlBlocked }, null, 2))
  console.log('TAB-01/02/03/04/05/06/08/09 editor, native restart and autosave passed')
  await evaluate(readFileSync('tests/macos-app-smoke.js', 'utf8'))
  const result = await waitFor(() => evaluate('window.__knowpaperSmokeResult'), 'native export and reader', 240000)
  writeFileSync(join(out, 'app-smoke.json'), JSON.stringify(result, null, 2))
  assert.equal(result.ok, true, result.error)
  assert.ok(result.tables?.paper && result.tables?.answers && result.tables?.pair)
  console.log(JSON.stringify(result))
  await close()
}
